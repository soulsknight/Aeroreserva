# Database
# https://docs.djangoproject.com/en/6.1/ref/settings/#databases

if os.environ.get('DJANGO_DB_ENGINE') == 'sqlite':
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / os.environ.get('SQLITE_DB_NAME', 'aero_reserva_test.sqlite3'),
        }
    }
else:
    database_url = os.environ.get('POSTGRES_URL') or os.environ.get('DATABASE_URL')
    if database_url:
        parsed_database_url = urlparse(database_url)
        if parsed_database_url.scheme not in ('postgres', 'postgresql'):
            raise ValueError('POSTGRES_URL debe usar el esquema postgres:// o postgresql://.')

        query = parse_qs(parsed_database_url.query)
        DATABASES = {
            'default': {
                'ENGINE': 'django.db.backends.postgresql',
                'NAME': unquote(parsed_database_url.path.lstrip('/')),
                'USER': unquote(parsed_database_url.username or ''),
                'PASSWORD': unquote(parsed_database_url.password or ''),
                'HOST': parsed_database_url.hostname or '',
                'PORT': parsed_database_url.port or '5432',
                'OPTIONS': {
                    'sslmode': query.get('sslmode', ['require'])[0],
                },
            }
        }
    else:
        DATABASES = {
            'default': {
                'ENGINE': 'django.db.backends.postgresql',
                'NAME': os.environ.get('POSTGRES_DB', 'aero_reserva_db'),
                'USER': os.environ.get('POSTGRES_USER', 'aero_user'),
                'PASSWORD': os.environ.get('POSTGRES_PASSWORD', ''),
                'HOST': os.environ.get('POSTGRES_HOST', 'localhost'),
                'PORT': os.environ.get('POSTGRES_PORT', '5432'),
            }
        }


